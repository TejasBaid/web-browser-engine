//! The fragment tree: the output of layout and the input of painting.

use super::{Edges, Rect};
use crate::dom::{Document, NodeId};
use crate::image::Image;
use crate::style::computed::ComputedStyle;
use crate::text::{FaceId, FontMetrics};
use std::fmt::Write;
use std::rc::Rc;

/// A positioned glyph inside a [`TextRun`].
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct PositionedGlyph {
    /// Face.
    pub face: FaceId,
    /// Glyph id.
    pub glyph: u16,
    /// Pen x relative to the run's left edge.
    pub x: f32,
    /// Vertical offset from the baseline (positive = down).
    pub y: f32,
}

/// A run of shaped text on one line.
#[derive(Clone, Debug, PartialEq)]
pub struct TextRun {
    /// Glyphs with positions.
    pub glyphs: Vec<PositionedGlyph>,
    /// Font size in px.
    pub font_size: f32,
    /// Distance from the fragment's top edge to the baseline.
    pub baseline: f32,
    /// Font metrics (for decorations).
    pub metrics: FontMetrics,
    /// The source text (for debugging and hit testing).
    pub text: String,
}

/// What a fragment represents.
#[derive(Clone, Debug, PartialEq)]
pub enum FragmentKind {
    /// The initial containing block; root of the tree.
    Viewport,
    /// A box generated by an element (block, inline-block, flex/table container, ...).
    Box,
    /// An anonymous box (anonymous block wrapper, anonymous table parts).
    Anonymous,
    /// A line box (not painted).
    Line,
    /// One line's portion of an inline box. `start`/`end` say whether the box's
    /// inline-start/end edges (border, padding, margin) are on this fragment.
    Inline {
        /// Has the start edge.
        start: bool,
        /// Has the end edge.
        end: bool,
    },
    /// Shaped text.
    Text(Rc<TextRun>),
    /// A replaced element's content (`rect` is the content box).
    Image(Option<Rc<Image>>),
    /// A list marker drawn as text.
    Marker(Rc<TextRun>),
    /// Placeholder for an absolutely positioned box at its static position.
    AbsPlaceholder(usize),
}

/// A positioned piece of the layout.
#[derive(Clone, Debug)]
pub struct Fragment {
    /// Kind.
    pub kind: FragmentKind,
    /// Generating DOM node (the element for pseudo-elements and anonymous boxes' parent
    /// is not recorded).
    pub node: Option<NodeId>,
    /// Style used for painting.
    pub style: Rc<ComputedStyle>,
    /// Border box, relative to the parent fragment's border-box origin.
    pub rect: Rect,
    /// Used margins (informational).
    pub margin: Edges,
    /// Used border widths.
    pub border: Edges,
    /// Used padding.
    pub padding: Edges,
    /// Child fragments in paint order (before stacking-context reordering).
    pub children: Vec<Fragment>,
    /// First baseline, relative to the top of the border box.
    pub first_baseline: Option<f32>,
    /// Last baseline, relative to the top of the border box.
    pub last_baseline: Option<f32>,
    /// Relative-position offset to apply (resolved during layout, applied by
    /// [`super::positioned`]).
    pub rel_offset: (f32, f32),
    /// Positioned relative to the viewport (`position: fixed`); doesn't scroll.
    pub fixed: bool,
    /// Borders resolved by the collapsing border model (table cells), painted centred
    /// on the border-box edges instead of the box's own borders.
    pub collapsed_border: Option<Box<CollapsedBorder>>,
}

/// A cell's collapsed borders: full widths, centred on the cell's border-box edges.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct CollapsedBorder {
    /// Full collapsed widths (top, right, bottom, left).
    pub widths: Edges,
    /// Colors.
    pub colors: [crate::css::color::Color; 4],
    /// Styles.
    pub styles: [crate::style::computed::BorderStyle; 4],
}

impl Fragment {
    /// Creates a fragment with no edges or children.
    pub fn new(kind: FragmentKind, node: Option<NodeId>, style: Rc<ComputedStyle>, rect: Rect) -> Fragment {
        Fragment {
            kind,
            node,
            style,
            rect,
            margin: Edges::default(),
            border: Edges::default(),
            padding: Edges::default(),
            children: Vec::new(),
            first_baseline: None,
            last_baseline: None,
            rel_offset: (0.0, 0.0),
            fixed: false,
            collapsed_border: None,
        }
    }

    /// The padding box, relative to this fragment's border-box origin.
    pub fn padding_box(&self) -> Rect {
        Rect::new(
            self.border.left,
            self.border.top,
            (self.rect.width - self.border.horizontal()).max(0.0),
            (self.rect.height - self.border.vertical()).max(0.0),
        )
    }

    /// The content box, relative to this fragment's border-box origin.
    pub fn content_box(&self) -> Rect {
        self.padding_box().inset(&self.padding)
    }

    /// Union of this fragment's border box and all descendants (in this fragment's
    /// parent's coordinate space), ignoring clipping.
    pub fn scrollable_overflow(&self) -> Rect {
        let mut r = self.rect;
        for c in &self.children {
            let cr = c.scrollable_overflow().translate(self.rect.x, self.rect.y);
            if cr.width > 0.0 || cr.height > 0.0 {
                r = r.union(&cr);
            }
        }
        r
    }

    /// Finds the first fragment generated by `node` (pre-order) and returns its border
    /// box in absolute coordinates.
    pub fn find_rect(&self, node: NodeId) -> Option<Rect> {
        self.find_rect_at(node, 0.0, 0.0)
    }

    fn find_rect_at(&self, node: NodeId, ox: f32, oy: f32) -> Option<Rect> {
        let abs = self.rect.translate(ox, oy);
        if self.node == Some(node)
            && !matches!(
                self.kind,
                FragmentKind::Text(_) | FragmentKind::Line | FragmentKind::AbsPlaceholder(_)
            )
        {
            return Some(abs);
        }
        self.children.iter().find_map(|c| c.find_rect_at(node, abs.x, abs.y))
    }

    /// All fragments generated by `node` (e.g. one per line for inline boxes), as
    /// absolute border boxes.
    pub fn find_all_rects(&self, node: NodeId) -> Vec<Rect> {
        let mut out = Vec::new();
        self.collect_rects(node, 0.0, 0.0, &mut out);
        out
    }

    fn collect_rects(&self, node: NodeId, ox: f32, oy: f32, out: &mut Vec<Rect>) {
        let abs = self.rect.translate(ox, oy);
        if self.node == Some(node)
            && !matches!(
                self.kind,
                FragmentKind::Text(_) | FragmentKind::Line | FragmentKind::AbsPlaceholder(_)
            )
        {
            out.push(abs);
        }
        for c in &self.children {
            c.collect_rects(node, abs.x, abs.y, out);
        }
    }

    /// Visits every fragment with its absolute border box.
    pub fn walk(&self, f: &mut impl FnMut(&Fragment, Rect)) {
        self.walk_at(0.0, 0.0, f);
    }

    fn walk_at(&self, ox: f32, oy: f32, f: &mut impl FnMut(&Fragment, Rect)) {
        let abs = self.rect.translate(ox, oy);
        f(self, abs);
        for c in &self.children {
            c.walk_at(abs.x, abs.y, f);
        }
    }
}

/// Writes an indented dump of the fragment tree.
pub fn dump(f: &Fragment, doc: &Document, ox: f32, oy: f32, depth: usize, out: &mut String) {
    let abs = f.rect.translate(ox, oy);
    let indent = "  ".repeat(depth);
    let name = f
        .node
        .map(|n| {
            let t = doc.tag_name(n);
            if t.is_empty() {
                "#text".to_string()
            } else {
                t.to_string()
            }
        })
        .unwrap_or_else(|| "anon".to_string());
    let kind = match &f.kind {
        FragmentKind::Viewport => "Viewport".to_string(),
        FragmentKind::Box => format!("Box <{name}>"),
        FragmentKind::Anonymous => "AnonymousBox".to_string(),
        FragmentKind::Line => "Line".to_string(),
        FragmentKind::Inline { start, end } => format!(
            "Inline <{name}>{}{}",
            if *start { "" } else { " (cont)" },
            if *end { "" } else { " (split)" }
        ),
        FragmentKind::Text(t) => format!("Text {:?}", truncate(&t.text, 50)),
        FragmentKind::Image(i) => format!(
            "Image <{name}>{}",
            i.as_ref()
                .map(|i| format!(" {}x{}", i.width, i.height))
                .unwrap_or_default()
        ),
        FragmentKind::Marker(t) => format!("Marker {:?}", t.text),
        FragmentKind::AbsPlaceholder(_) => "AbsPlaceholder".to_string(),
    };
    let _ = writeln!(
        out,
        "{indent}{kind} ({:.1}, {:.1}) {:.1}x{:.1}{}",
        abs.x,
        abs.y,
        abs.width,
        abs.height,
        if f.fixed { " fixed" } else { "" }
    );
    for c in &f.children {
        dump(c, doc, abs.x, abs.y, depth + 1, out);
    }
}

fn truncate(s: &str, n: usize) -> String {
    if s.chars().count() <= n {
        s.to_string()
    } else {
        format!("{}…", s.chars().take(n).collect::<String>())
    }
}
