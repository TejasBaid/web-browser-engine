#!/usr/bin/env python3
"""Generate src/html/entities.rs from the WHATWG entities.json table.

Usage: curl -sSLO https://html.spec.whatwg.org/entities.json
       python3 scripts/gen_entities.py entities.json > src/html/entities.rs
"""
import json
import sys

table = json.load(open(sys.argv[1]))
entries = sorted((name[1:], "".join(chr(c) for c in v["codepoints"])) for name, v in table.items())


def lit(s):
    return "".join(c if 0x20 <= ord(c) < 0x7F and c not in '"\\' else "\\u{%x}" % ord(c) for c in s)


print("//! Named character references, generated by `scripts/gen_entities.py` from")
print("//! <https://html.spec.whatwg.org/entities.json>. Do not edit by hand.")
print("")
print("/// `(name without the leading '&', replacement)`, sorted by name (byte order).")
print("/// Names that are valid without a trailing semicolon appear twice, with and without it.")
print("pub static ENTITIES: &[(&str, &str)] = &[")
for name, chars in entries:
    print('    ("%s", "%s"),' % (lit(name), lit(chars)))
print("];")
print("")
print("/// Length in bytes of the longest entity name.")
print("pub const MAX_ENTITY_LEN: usize = %d;" % max(len(n) for n, _ in entries))
